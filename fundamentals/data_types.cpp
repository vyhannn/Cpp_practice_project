#include <iostream>

using namespace std;

int main()
{
    // To create a variable that stores an character we use the "char" data type. 
    char myChar = 'A';


    // Data type "string" stores a sequence of characters.
    string myString = "Learning C++!";


    // Data type "integer" stores whole numbers.
    int myInt = 17;


    // Data type "float" stores decimal numbers that are less precise than "double".
    // Usually use "f" at the end of the number to indicate it is a float data type.
    float myFloat = 3.14f;


    // Data type "double" stores decimal numbers that are more precise than "float".
    double myDouble = 3.141592653589793;

    // Data type "bool" stores boolean values, which mean they can only store true or false.
    bool myBool = true;

    return 0;
}